  id, session_id, reviewer_user_id, reviewee_user_id, rating, badges
)
SELECT
  gen_random_uuid(),
  s.id AS session_id,
  r.user_id AS reviewer_user_id,
  r2.user_id AS reviewee_user_id,
  5,
  ARRAY['準時王', '神對手']
FROM sessions s
JOIN session_registrations r  ON r.session_id = s.id
JOIN session_registrations r2 ON r2.session_id = s.id
  AND r2.user_id <> r.user_id
  AND r2.user_id IN (
    '00000000-0000-0000-0002-000000000001',
    '00000000-0000-0000-0002-000000000002'
  )
WHERE s.status = 'completed'
  AND s.id IN (
    '00000000-0000-0000-0006-000000000001',
    '00000000-0000-0000-0006-000000000002',
    '00000000-0000-0000-0006-000000000005',
    '00000000-0000-0000-0006-000000000006',
    '00000000-0000-0000-0006-000000000009',
    '00000000-0000-0000-0006-000000000010'
  )
ON CONFLICT (session_id, reviewer_user_id, reviewee_user_id) DO NOTHING;
